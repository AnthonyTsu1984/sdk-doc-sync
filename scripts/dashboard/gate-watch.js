'use strict';

// Batch-14 doorbell: turn the dashboard's aggregated payload into
// operator-actionable notification events and decide which of them actually
// get sent on a sweep. The dashboard keeps no second truth — every event
// derives from fields the cards already show; sending decisions persist to an
// append-only ledger under tmp/dashboard-events/ so a restart neither
// re-spams nor forgets. Pure functions only: the server owns all IO.

const fs = require('node:fs');
const path = require('node:path');

const ROLLBACK_MANIFESTS_RELATIVE_DIR = 'tmp/api-reference-sync/rollback-manifests';
// Canonical gate-presentation output root (relay v2 slice A producer): the
// per-session index.json files live under <root>/<sessionKey>/, the board
// mirrors under <root>/latest.html + latest-index.json.
const GATE_PRESENTATION_RELATIVE_DIR = 'tmp/api-reference-sync/gate-presentation';

// Relay-actionable category per gate (line vocabulary). The campaign gate is
// the single approval surface; rollback is a unit-scoped destructive-op
// confirmation riding the same channel.
const GATE_CATEGORY_BY_LINE_GATE = Object.freeze({
  APPROVE_ROLLBACK: '战役门',
  APPROVE_CAMPAIGN: '战役门',
});

// 2026-10-01 会话轮换裁定: rotate conversations at 42% context usage. For
// headless workers the board approximates context with the latest turn's
// reprocessed input (fresh input + cache read); past the advisory a long turn
// is burning mostly context carriage (once: 115M tokens / 249 turns).
const CONTEXT_LIMIT_TOKENS = 1_000_000; // tune to the worker model's window
const CONTEXT_ROTATION_FRACTION = 0.42;

function contextTokensOf(worker) {
  return typeof worker?.contextTokens === 'number' ? worker.contextTokens : null;
}

// A rollback gate the session status machine cannot see: the worker planned
// the rollback (manifest on disk) but the wait-for-operator state lives only
// in the worker conversation — the session file has no activeRollback until
// execution. The board therefore derives the gate from the manifest itself:
// pending while the anchored journal still sits in its slot (rollback
// completion byte-archives it away), closed once the slot is released or the
// manifest is cleaned up.
function pendingRollbackGateFor(repoRoot, sessionId, executedManifestDigests = null, unitId = null) {
  if (!repoRoot || !sessionId) return null;
  const dir = path.join(repoRoot, ROLLBACK_MANIFESTS_RELATIVE_DIR);
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch {
    return null;
  }
  for (const name of names) {
    if (!name.endsWith('.json')) continue;
    let manifest;
    try {
      manifest = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
    } catch {
      continue;
    }
    if (manifest.sessionId !== sessionId) continue;
    // Pre-staged manifests exist for units that are not the machine's
    // current blocker — only the unit the session machine points at is a
    // live gate.
    if (unitId && manifest.reviewUnitId !== unitId) continue;
    // A receipt binding this manifest digest means the rollback already
    // executed — the gate is closed regardless of journal archiving (the
    // supersede path rewrites the slot instead of archiving it).
    if (executedManifestDigests && executedManifestDigests.has(manifest.rollbackManifestDigest)) continue;
    if (!manifest.reviewUnitId || !manifest.rollbackManifestDigest) continue;
    if (typeof manifest.executionJournalPath !== 'string') continue;
    try {
      fs.statSync(manifest.executionJournalPath);
    } catch {
      continue; // anchored journal already archived — rollback completed
    }
    return {
      gate: 'APPROVE_ROLLBACK',
      reviewUnitId: manifest.reviewUnitId,
      digest: manifest.rollbackManifestDigest,
      manifestPath: `${ROLLBACK_MANIFESTS_RELATIVE_DIR}/${name}`,
      source: 'rollback-manifest',
    };
  }
  return null;
}

// The canonical gate-presentation artifact (gate-presentation/latest.html,
// regenerated by the worker's gate-presentation.js at every formal 呈门).
// The board parses it to show the operator WHAT a gate approves — the digest
// line remains the only binding, links here are convenience and are dropped
// on any mismatch (gate kind or session path). Write-gate links are local
// dry-run preview files (file://) while document gates carry live record
// links (https://) — both shapes are captured.
function parseGatePresentation(html) {
  if (typeof html !== 'string') return null;
  const gateMatch = /<h1>(APPROVE_[A-Z_]+)\s*—/.exec(html);
  const digestMatch = /bound digest:\s*<code>(sha256:[a-f0-9]{64})<\/code>/.exec(html);
  const sessionMatch = /session:\s*<code>([^<]+)<\/code>/.exec(html);
  const generatedMatch = /generated:\s*([0-9T:.\-Z]+)/.exec(html);
  if (!gateMatch || !digestMatch || !sessionMatch) return null;
  const links = [];
  const item = /<a href="((?:https?|file):\/\/[^"]+)">\s*\d+\.\s*([\w:.-]+)\s*—/g;
  let m;
  while ((m = item.exec(html)) !== null) links.push({ unitId: m[2], url: m[1] });
  return {
    gate: gateMatch[1],
    digest: digestMatch[1],
    sessionPath: sessionMatch[1].trim(),
    generatedAt: generatedMatch ? generatedMatch[1] : null,
    links,
  };
}


function presentationMatchesCard(parsed, card) {
  if (!parsed || !card?.nextGate?.gate) return false;
  const lineGate = card.nextGate.gate;
  if (parsed.gate !== lineGate) return false;
  return parsed.sessionPath === card.sessionPath;
}

// ---------- presentation index.json (relay v2 slice B consumption) ----------
//
// The producer (.claude/skills/api-reference-sync/.../gate-presentation.js)
// writes `<sessionKey>/<YYYYMMDD-HHMMSS>-<gate>.index.json` machine truth next
// to each human card. The index REPLACES scraped HTML as the approval binding:
// its replyLines are the only lines a consumer may act on, and its digest is
// carried (never computed). Shape checks here are consumer-side admission
// only — the producer's own validator (gate-presentation-check.js) is the
// re-derivation authority.

// Mirror of the producer's sessionKeyOf (gate-presentation.js): injective,
// filesystem-safe — two sessions can never share an output directory.
function presentationSessionKey(sessionPath) {
  if (typeof sessionPath !== 'string' || sessionPath.trim() === '') return null;
  return sessionPath.split(path.sep).join('/').replace(/[^A-Za-z0-9._-]/g, '-');
}

// Consumer-side admission: an index that does not carry gate + session +
// string replyLines (and a null-or-sha256 digest) is not a binding surface.
function parsePresentationIndex(raw) {
  if (typeof raw !== 'string') return null;
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return null;
  if (typeof parsed.gate !== 'string' || !/^APPROVE_[A-Z_]+$/.test(parsed.gate)) return null;
  if (typeof parsed.sessionPath !== 'string' || parsed.sessionPath.trim() === '') return null;
  if (!Array.isArray(parsed.replyLines) || parsed.replyLines.some((line) => typeof line !== 'string' || line === '')) return null;
  if (parsed.digest !== null && parsed.digest !== undefined
    && (typeof parsed.digest !== 'string' || !/^sha256:[a-f0-9]{64}$/.test(parsed.digest))) return null;
  return parsed;
}

// Newest *.index.json by mtime. Atomic-write tmp siblings are named
// `<stem>.index.json.tmp-<pid>-<ms>` — they never END with `.index.json`, and
// the explicit `.tmp-` guard keeps that contract obvious.
function latestIndexEntryFrom(entries) {
  let best = null;
  for (const entry of Array.isArray(entries) ? entries : []) {
    if (!entry || typeof entry.name !== 'string') continue;
    if (!entry.name.endsWith('.index.json')) continue;
    if (entry.name.includes('.tmp-')) continue;
    const mtimeMs = typeof entry.mtimeMs === 'number' ? entry.mtimeMs : 0;
    if (!best || mtimeMs > best.mtimeMs) best = { name: entry.name, mtimeMs };
  }
  return best;
}

// Read the newest presentation index bound to a session. Returns
// { path (repo-relative posix), parsed, mtimeMs } or null. IO lives here (the
// same allowance as pendingRollbackGateFor): the server calls it during card
// enrichment, tests call it against fixture roots.
function readLatestPresentationIndex(repoRoot, sessionPath, dir = GATE_PRESENTATION_RELATIVE_DIR) {
  const key = presentationSessionKey(sessionPath);
  if (!key || !repoRoot) return null;
  const sessionDir = path.join(repoRoot, dir, key);
  let dirents;
  try {
    dirents = fs.readdirSync(sessionDir, { withFileTypes: true });
  } catch {
    return null;
  }
  const entries = [];
  for (const dirent of dirents) {
    if (!dirent.isFile()) continue;
    let mtimeMs = 0;
    try {
      mtimeMs = fs.statSync(path.join(sessionDir, dirent.name)).mtimeMs;
    } catch {
      mtimeMs = 0;
    }
    entries.push({ name: dirent.name, mtimeMs });
  }
  const latest = latestIndexEntryFrom(entries);
  if (!latest) return null;
  const absolute = path.join(sessionDir, latest.name);
  let raw = null;
  try {
    raw = fs.readFileSync(absolute, 'utf8');
  } catch {
    return null;
  }
  const parsed = parsePresentationIndex(raw);
  if (!parsed) return null;
  const relative = path.relative(repoRoot, absolute).split(path.sep).join('/');
  return { path: relative, parsed, mtimeMs: latest.mtimeMs };
}

// UI-compat view of an index: the same shape the legacy HTML scraper produced
// ({gate, digest, sessionPath, generatedAt, links:[{unitId, url}]}) so the
// board page keeps rendering links/digest unchanged when the attachment is
// index-backed.
function presentationViewFromIndex(index) {
  if (!index || typeof index !== 'object') return null;
  const links = [];
  for (const unit of Array.isArray(index.units) ? index.units : []) {
    for (const link of Array.isArray(unit?.links) ? unit.links : []) {
      links.push({ unitId: unit?.reviewUnitId ?? null, url: link });
    }
  }
  return {
    gate: index.gate,
    digest: index.digest ?? null,
    sessionPath: index.sessionPath,
    generatedAt: typeof index.generatedAt === 'string' ? index.generatedAt : null,
    links,
  };
}

function readFileOrNull(absolutePath) {
  try {
    return fs.readFileSync(absolutePath, 'utf8');
  } catch {
    return null;
  }
}

// Attach the current gate's presentation to a campaign card — slice B: the
// per-session index.json is preferred (it is the approval binding); the
// legacy latest.html scraper remains the fallback so pre-index artifacts keep
// attaching. Matching semantics unchanged: gate kind (line vocabulary) +
// session path must both agree, any mismatch drops the attachment. A parse
// blip mid-rewrite still rides the last-known-good grace window.
//
// `lkg` is the caller-owned Map (card.sessionPath -> {kind, path?, parsed,
// at}) so the server keeps one LKG store across recomputes.
function attachPresentationToCard(card, { repoRoot, lkg = new Map(), graceMs = 60_000, now = Date.now(), dir = GATE_PRESENTATION_RELATIVE_DIR } = {}) {
  card.gatePresentation = null;
  card.gatePresentationIndex = null;
  if (!card.nextGate || !card.nextGate.gate || !repoRoot) return card;

  const indexRead = readLatestPresentationIndex(repoRoot, card.sessionPath, dir);
  if (indexRead && presentationMatchesCard(indexRead.parsed, card)) {
    lkg.set(card.sessionPath, { kind: 'index', path: indexRead.path, parsed: indexRead.parsed, at: now });
    card.gatePresentationIndex = { path: indexRead.path, parsed: indexRead.parsed };
    card.gatePresentation = presentationViewFromIndex(indexRead.parsed);
    return card;
  }

  // Legacy fallback: the global latest.html mirror (pre-index producers).
  const parsed = parseGatePresentation(readFileOrNull(path.join(repoRoot, dir, 'latest.html')));
  if (parsed) {
    if (presentationMatchesCard(parsed, card)) {
      lkg.set(card.sessionPath, { kind: 'html', parsed, at: now });
      card.gatePresentation = parsed;
    }
    return card;
  }

  // Both reads blipped (mid-rewrite): serve the last known good match briefly.
  const last = lkg.get(card.sessionPath);
  if (last && now - last.at < graceMs && presentationMatchesCard(last.parsed, card)) {
    if (last.kind === 'index') {
      card.gatePresentationIndex = { path: last.path, parsed: last.parsed };
      card.gatePresentation = presentationViewFromIndex(last.parsed);
    } else {
      card.gatePresentation = last.parsed;
    }
  }
  return card;
}

// Re-notify a still-pending event at most every 2h (dwell escalation).
const ESCALATE_AFTER_MS = 2 * 60 * 60 * 1000;
// Quiet window 22:00–07:59 local: sweeps still record resolve bookkeeping but
// send nothing — unsent events accumulate naturally and land as one merged
// message on the first morning sweep.
const QUIET_START_HOUR = 22;
const QUIET_END_HOUR = 8;
// A dispatched intake worker with no exit record: worth one notification once
// it outlives the 2h in-flight cap, silence after a day (the campaign card or
// a fresh dispatch has superseded it by then).
const LOST_WORKER_MIN_AGE_MS = 2 * 60 * 60 * 1000;
const LOST_WORKER_MAX_AGE_MS = 24 * 60 * 60 * 1000;

function inQuietWindow(date) {
  const hour = date.getHours();
  return hour >= QUIET_START_HOUR || hour < QUIET_END_HOUR;
}

function workerContextEvents(payload) {
  const events = [];
  for (const card of payload?.campaigns || []) {
    for (const worker of card.workers || []) {
      if (!worker || worker.status !== 'running') continue;
      const contextTokens = contextTokensOf(worker);
      if (contextTokens == null) continue;
      if (contextTokens < CONTEXT_LIMIT_TOKENS * CONTEXT_ROTATION_FRACTION) continue;
      events.push({
        key: `context:${card.sessionKey ?? `main::${card.sessionPath}`}:${worker.sessionId}`,
        category: '会话过重',
        line: `${cardLabel(card)} worker 上下文 ≈${Math.round(contextTokens / 1000)}k tokens——超 42% 轮换约定，建议它停门后「一键派出执行会话」换新会话续接`,
        since: null,
      });
    }
  }
  return events;
}

function cardLabel(card) {
  const track = card.track ? ` ${card.track}` : '';
  const checkout = card.checkoutLabel ? `（${card.checkoutLabel}）` : '';
  return `${card.language ?? '未知语言'}${track}${checkout}`;
}

// One event per actionable finding. `since` carries the durable timestamp the
// dwell is measured from (gate presentation, worker dispatch, sentinel last
// run) — not "when the notifier first noticed", which would understate waits
// across restarts.
// Relay-actionable gate events (slice B): when the card carries an attached
// presentation INDEX (the approval binding) and no worker is running (the
// worker is parked AT the gate), the gate becomes approvable from the p2p
// chat — one event per reply line, carrying everything a reply needs to bind
// WITHOUT trusting message text: the index path, the verbatim replyLine, the
// carried digest, and (when exactly one idle board worker holds the session)
// the sessionId binding. Multi-unit acceptance gates emit one event per unit
// (key contains the reviewUnitId) so a reply binds a single meaning.
// Cards without an index binding — or with a worker mid-turn — keep the
// legacy generic 战役门 event (board pointer, no reply binding).
function presentationGateEvents(card, { sessionKey, running }) {
  if (running) return [];
  const attached = card.gatePresentationIndex;
  const index = attached?.parsed ?? null;
  const indexPath = attached?.path ?? null;
  if (!index || !indexPath) return [];
  if (!presentationMatchesCard(index, card)) return [];
  const lineGate = card.nextGate.gate;
  const category = GATE_CATEGORY_BY_LINE_GATE[lineGate] ?? null;
  if (!category) return []; // a stray chip not carried by the campaign channel
  const lines = Array.isArray(index.replyLines) ? index.replyLines.filter((line) => typeof line === 'string' && line !== '') : [];
  if (lines.length === 0) return [];
  const idleWorkers = (card.workers || []).filter((w) => w && w.status === 'idle' && w.sessionId);
  const boundSessionId = idleWorkers.length === 1 ? idleWorkers[0].sessionId : null;
  // Unit-scoped rollback indexes carry one reply line per unit
  const perUnit = index.gate === 'APPROVE_ROLLBACK';
  const emitted = perUnit
    ? lines.map((line) => {
      const match = /^APPROVE_ROLLBACK (\S+) sha256:/.exec(line);
      return { line, unitId: match ? match[1] : null };
    })
    : [{ line: lines[0], unitId: card.nextGate.reviewUnitId ?? null }];
  return emitted.map(({ line, unitId }) => ({
    key: `gate:${sessionKey}:${lineGate}${unitId ? `:${unitId}` : ''}`,
    category,
    line: `${cardLabel(card)} 停在 ${lineGate}${unitId ? `（${unitId}）` : ''}——回复本通知发送「批准」即可批准${unitId ? '该单元' : '本门'}`,
    since: typeof index.generatedAt === 'string' ? index.generatedAt : (card.updatedAt ?? null),
    sessionPath: card.sessionPath ?? null,
    sessionKey,
    gate: lineGate,
    reviewUnitId: unitId ?? null,
    replyLine: line,
    digest: index.digest ?? null,
    indexId: indexPath,
    language: card.language ?? null,
    sessionId: boundSessionId,
  }));
}

function campaignEvents(payload, nowMs) {
  const events = [];
  for (const card of payload?.campaigns || []) {
    const sessionKey = card.sessionKey ?? `main::${card.sessionPath}`;
    if (card.health === 'zombie') {
      events.push({
        key: `zombie:${sessionKey}`,
        category: '僵尸会话',
        line: `${cardLabel(card)} 会话已标记僵尸（scan-state 已越过它）——处置或归档`,
        since: card.updatedAt ?? null,
      });
      continue; // a zombie needs no gate echo on top
    }
    if (card.health === 'awaiting-close') {
      events.push({
        key: `close:${sessionKey}`,
        category: '待关账',
        line: `${cardLabel(card)} 全部单元已验收——执行 close-session 收账`,
        since: card.updatedAt ?? null,
      });
      continue;
    }
    if (card.staleReceipts && card.staleReceipts.count > 0) {
      events.push({
        key: `stale-receipt:${sessionKey}`,
        category: '回执未落',
        line: `${cardLabel(card)} ${card.staleReceipts.count} 个单元执行完成但回执未落账——核对 journal 后补记`,
        since: card.updatedAt ?? null,
      });
    }
    const gate = card.nextGate && card.nextGate.gate;
    if (card.health === 'active' && gate && gate !== 'CLOSE_SESSION') {
      // A dispatched worker mid-turn may already hold this gate's approval —
      // "停在 X" alone reads as "waiting for the operator" and has repeatedly
      // sent the operator to re-approve during execution. Surface the worker.
      const running = (card.workers || []).some((w) => w && w.status === 'running');
      const rich = presentationGateEvents(card, { sessionKey, running });
      if (rich.length > 0) {
        events.push(...rich);
        continue;
      }
      events.push({
        key: `gate:${sessionKey}:${gate}`,
        category: '战役门',
        line: `${cardLabel(card)} 停在 ${gate}${card.nextGate.reviewUnitId ? `（${card.nextGate.reviewUnitId}）` : ''}${running ? ' — worker 执行中（批准可能已注入，等它停住再操作）' : ''}`,
        since: card.updatedAt ?? null,
      });
    }
  }
  return events;
}

// Unapproved intake campaign manifests: the campaign's first gate, often the
// longest wait (presented → operator approval can span days).
function intakeEvents(payload) {
  const events = [];
  for (const card of payload?.intakes || []) {
    if (card.approved) continue;
    events.push({
      key: `campaign:${card.manifestPath}`,
      category: '战役门',
      line: `${card.language ?? '未知语言'} 战役计划已呈门待批（${card.checkoutLabel ?? ''}）`,
      since: card.presentedAt ?? null,
    });
  }
  return events;
}

function sentinelEvents(payload) {
  const events = [];
  for (const sentinel of payload?.sentinels || []) {
    if (sentinel.status === 'stale') {
      events.push({
        key: `sentinel:${sentinel.id}:stale`,
        category: '哨兵停摆',
        line: `${sentinel.title} 超过 25h 未运行——查 cron 或失败原因`,
        since: sentinel.lastRunAt ?? null,
      });
    } else if (sentinel.status === 'never-run' && sentinel.readiness?.capabilityReady) {
      // capability-ready-but-never-ran means the schedule should have fired
      // and did not; a not-yet-ready sentinel is setup state, not news.
      events.push({
        key: `sentinel:${sentinel.id}:never`,
        category: '哨兵未跑',
        line: `${sentinel.title} 具备运行条件但从未运行——查 cron`,
        since: null,
      });
    }
  }
  return events;
}

// Open dispatches that outlived the in-flight cap: the child died without an
// exit record (crash, host reboot) and only the durable ledger remembers it.
function lostWorkerEvents(dispatchLines, nowMs) {
  const events = [];
  const lastByKey = new Map();
  for (const line of Array.isArray(dispatchLines) ? dispatchLines : []) {
    let parsed;
    try {
      parsed = JSON.parse(line);
    } catch {
      continue;
    }
    if (parsed && typeof parsed.workerKey === 'string') lastByKey.set(parsed.workerKey, parsed);
  }
  for (const [workerKey, last] of lastByKey) {
    if (last.kind === 'exit') continue;
    const dispatchedAt = Date.parse(last.at || '');
    if (!Number.isFinite(dispatchedAt)) continue;
    const age = nowMs - dispatchedAt;
    if (age < LOST_WORKER_MIN_AGE_MS || age > LOST_WORKER_MAX_AGE_MS) continue;
    events.push({
      key: `lost-worker:${workerKey}`,
      category: 'worker 失联',
      line: `派出的 intake worker（${workerKey}）超过 2h 无退出记录——确认进程或重新派单`,
      since: last.at ?? null,
    });
  }
  return events;
}

function deriveEvents({ payload, dispatchLines, now = new Date() }) {
  const nowMs = now.getTime();
  return [
    ...campaignEvents(payload, nowMs),
    ...intakeEvents(payload),
    ...sentinelEvents(payload),
    ...lostWorkerEvents(dispatchLines, nowMs),
    ...workerContextEvents(payload),
  ];
}

// Ledger lines (newest last): { v:1, key, at, kind: 'send'|'resolve' }. The
// latest record per key decides — a resolve forgets prior sends so a
// re-occurrence is new again.
function ledgerState(lines) {
  const state = new Map();
  for (const line of Array.isArray(lines) ? lines : []) {
    let parsed;
    try {
      parsed = JSON.parse(line);
    } catch {
      continue;
    }
    if (!parsed || typeof parsed.key !== 'string') continue;
    state.set(parsed.key, parsed);
  }
  return state;
}

function decideSends(events, ledgerLines, now = new Date(), { force = false } = {}) {
  const state = ledgerState(ledgerLines);
  const present = new Set(events.map((event) => event.key));
  const appends = [];
  for (const key of state.keys()) {
    const record = state.get(key);
    if (!present.has(key) && record.kind !== 'resolve') {
      appends.push({ v: 1, key, at: now.toISOString(), kind: 'resolve' });
    }
  }
  const sends = [];
  if (inQuietWindow(now) && !force) {
    return { sends, appends };
  }
  for (const event of events) {
    const record = state.get(event.key);
    const lastSend = record && record.kind === 'send' ? record : null;
    if (lastSend) {
      const sentAt = Date.parse(lastSend.at || '');
      if (Number.isFinite(sentAt) && now.getTime() - sentAt < ESCALATE_AFTER_MS) continue;
    }
    const since = Date.parse(event.since || '');
    const dwellMs = Number.isFinite(since) ? Math.max(0, now.getTime() - since) : null;
    sends.push({
      ...event,
      dwellMs,
      escalated: Boolean(lastSend),
    });
  }
  // The caller appends the matching send record per event only after the
  // message actually went out — a failed send must retry on the next sweep.
  return { sends, appends };
}

function formatDwell(dwellMs) {
  if (dwellMs === null || !Number.isFinite(dwellMs)) return '';
  const hours = dwellMs / 3_600_000;
  if (hours >= 48) return `已等待 ${Math.floor(hours / 24)} 天`;
  if (hours >= 1) return `已等待 ${hours.toFixed(1)} 小时`;
  return '刚发生';
}

// Plain text by construction: interactive cards render links AND bare URLs as
// unclickable text, and gate digests are display-only — the message carries
// neither, only enough to find the item on the board.
function formatMessage(sends, { generatedAt } = {}) {
  const lines = ['🔔 治理看板 · 待你决定'];
  if (sends.length === 1) {
    const [send] = sends;
    const dwell = formatDwell(send.dwellMs);
    lines.push(`【${send.category}】${send.line}${dwell ? ` — ${dwell}` : ''}${send.escalated ? '（再次提醒）' : ''}`);
  } else {
    sends.forEach((send, index) => {
      const dwell = formatDwell(send.dwellMs);
      lines.push(`${index + 1}. 【${send.category}】${send.line}${dwell ? ` — ${dwell}` : ''}${send.escalated ? '（再次提醒）' : ''}`);
    });
  }
  const stamp = generatedAt ? new Date(generatedAt).toLocaleString('zh-CN', { hour12: false }) : null;
  lines.push('——到任务看板处理；本消息不含链接与摘要，一切以看板和 canonical CLI 呈现的绑定工件为准。');
  if (stamp) lines.push(`（看板扫描于 ${stamp}）`);
  return lines.join('\n');
}

